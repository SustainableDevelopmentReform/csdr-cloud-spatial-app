function toFormTimePoint(timePoint: Date | string | null | undefined) {
  if (!timePoint) return null
  return timePoint instanceof Date ? timePoint.toISOString() : timePoint
}

function toTimePointSortValue(timePoint: string) {
  const value = new Date(timePoint).getTime()
  return Number.isFinite(value) ? value : Number.MAX_SAFE_INTEGER
}

function normalizeAutoGeneratedTitle(title: string | null | undefined) {
  return (
    title
      ?.trim()
      .replace(
        /^(Percent change|Change) over time:\s+(.+)\s+—\s+([^—]+ to [^—]+)$/,
        '$1 from $3: $2',
      )
      .replace(
        /^(Percent change|Change) between consecutive time points:/,
        '$1 from previous time point:',
      )
      .replace(/\s+[—-]\s+/g, ' — ')
      .replace(/\s+/g, ' ') ?? ''
  )
}

function matchesAutoGeneratedTitle(
  title: string | null | undefined,
  suggestedTitle: string | null | undefined,
) {
  const normalizedTitle = normalizeAutoGeneratedTitle(title)
  const normalizedSuggestedTitle = normalizeAutoGeneratedTitle(suggestedTitle)
  return normalizedTitle !== '' && normalizedTitle === normalizedSuggestedTitle
}

